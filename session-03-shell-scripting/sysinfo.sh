# ---- variables ----
CURRENT_DATE=$(date)
HOST_NAME=$(hostname)
USER_NAME=$(whoami)

echo "=========================================="
echo "        SYSTEM INFORMATION REPORT"
echo "=========================================="

echo "Date      : $CURRENT_DATE"
echo "Hostname  : $HOST_NAME"
echo "Username  : $USER_NAME"

echo ""
echo "---------- Disk Usage ----------"
df -h /

echo ""
echo "---------- Running Processes (top 10) ----------"
ps aux | head -n 11

echo ""
# ---- user input ----
read -p "Enter a name for the report directory: " DIR_NAME
read -p "Enter a name for the report file: " FILE_NAME

mkdir -p "$DIR_NAME"
echo "Directory '$DIR_NAME' created."

touch "$DIR_NAME/$FILE_NAME"
echo "File '$DIR_NAME/$FILE_NAME' created."

# ---- save running processes to the file ----
ps aux > "$DIR_NAME/$FILE_NAME"
echo "Running processes saved to $DIR_NAME/$FILE_NAME ($(wc -l < "$DIR_NAME/$FILE_NAME") lines)"

echo "=========================================="
echo "Report generated by $USER_NAME on $HOST_NAME"
